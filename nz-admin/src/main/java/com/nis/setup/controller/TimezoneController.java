    private static final List<Timezone> SYS_TIMEZONE_LIST;

    @GetMapping
    public R queryList(@RequestParam(required = false) String name) {
        name = Tool.StrUtil.trim(name);
        if (Tool.StrUtil.isNotEmpty(name)) {
            String finalName = name;
            List<Timezone> tList = SYS_TIMEZONE_LIST.stream()
                    .filter(timezone -> Tool.StrUtil.containsIgnoreCase(timezone.getName(), finalName))
                    .collect(Collectors.toList());
            return R.ok().putData("list", tList);
        }
        return R.ok().putData("list", SYS_TIMEZONE_LIST);
    }

    /**
     * query Timezone By Name
     *
     * @param name
     * @return
     */
    public static Timezone queryTimezoneByName(String name) {
        Timezone timezone = SYS_TIMEZONE_LIST.stream()
                .filter(entity -> Tool.StrUtil.equals(entity.getName(), name))
                .findFirst()
                .orElse(null);
        return timezone;
    }

